test('fetchIdentity separates a signed-in user from an anonymous session', async () => {
  const signedIn = await health.fetchIdentity({ token: 't', cookie: 'c' }, {
    fetchImpl: async () => res(JSON.stringify({
      code: 0,
      data: { biz_code: 0, biz_data: { id: 'user-1', email: 'me@example.com', mobile: null } },
    })),
  });
  assert.deepEqual(
    { loggedIn: signedIn.loggedIn, email: signedIn.email, verified: signedIn.verified },
    { loggedIn: true, email: 'me@example.com', verified: true },
  );

  const anonymous = await health.fetchIdentity({ token: '', cookie: 'ds_session_id=abc' }, {
    fetchImpl: async () => res('<html><title>DeepSeek</title>sign in</html>'),
  });
  assert.equal(anonymous.loggedIn, false);
  assert.equal(anonymous.verified, true, 'the server answered, so this really is not a login');

  const offline = await health.fetchIdentity({ token: 't', cookie: 'c' }, {
    fetchImpl: async () => { throw new Error('EAI_AGAIN'); },
  });
  assert.equal(offline.loggedIn, false);
  assert.equal(offline.verified, false, 'no answer means unverified, not anonymous');
});

// ---------------------------------------------------------------------------
// The refresh queue: one browser per account, with a cool-down
// ---------------------------------------------------------------------------

test('the auto-refresher runs once per file and dedupes concurrent triggers', async () => {
  let clock = 1000;
  const ran = [];
  const refreshed = [];
  let release;
  const gate = new Promise((resolve) => { release = resolve; });
  const refresher = health.createWafAutoRefresher({
    now: () => clock,
    cooldownMs: 60_000,
    runRefresh: async (file) => { ran.push(file); await gate; return true; },
    onRefreshed: async ({ file }) => { refreshed.push(file); },
  });

  const first = refresher.trigger('/tmp/a.json');
  const second = refresher.trigger('/tmp/a.json');
  assert.equal(first.started, true);
  assert.equal(second.started, false);
  assert.equal(second.reason, 'in_flight');
  assert.equal(ran.length, 1, 'a burst of 401s must not spawn a browser per request');

  release();
  assert.equal(await first.promise, true);
  assert.deepEqual(refreshed, ['/tmp/a.json']);

  // Cooled down: no second browser run for the same file.
  clock += 1000;
  const third = refresher.trigger('/tmp/a.json');
  assert.equal(third.started, false);
  assert.equal(third.reason, 'cooldown');
  assert.ok(third.retryInMs > 0);

  // Once the cool-down elapses it is allowed to try again.
  clock += 60_000;
  assert.equal(refresher.trigger('/tmp/a.json').started, true);
});

test('a failed refresh is recorded and does not report success', async () => {
  const errors = [];
  const refresher = health.createWafAutoRefresher({
    now: () => 0,
    cooldownMs: 1000,
    runRefresh: async () => { throw new Error('browser died'); },
    onError: (err) => errors.push(err.message),
  });
  const run = refresher.trigger('/tmp/b.json');
  assert.equal(await run.promise, false);
  assert.deepEqual(errors, ['browser died']);
  assert.equal(refresher.history()[0].ok, false);
});

// ---------------------------------------------------------------------------
// Server wiring: WAF 401s refresh, auth 401s do not, throttles back off
// ---------------------------------------------------------------------------

function fakeRefresher() {
  const triggered = [];
  return {
    triggered,
    refresher: {
      trigger: (file) => { triggered.push(file); return { started: true, promise: Promise.resolve(true) }; },
      isRunning: () => false,
      history: () => [],
    },
  };
}

test('a WAF 401 parks the login briefly and queues its token refresh', () => {
  const fake = fakeRefresher();
  const restore = S.useWafRefresher(fake.refresher);
  try {
    const account = { id: 'waf', file: '/tmp/accounts/waf.json', config: {}, cooldownUntil: 0, failures: 0 };
    S.markAccountFailure(account, 401, 'completion', null, CLOUDFRONT_BLOCK);
    assert.equal(account.cooldownReason, 'waf');
    const remaining = account.cooldownUntil - Date.now();
    assert.ok(remaining > 0 && remaining <= 31_000, `short cooldown, got ${remaining}ms`);
    assert.deepEqual(fake.triggered, ['/tmp/accounts/waf.json']);
  } finally {
    restore();
  }
});

test('a real auth rejection still parks the login for a full cooldown and refreshes nothing', () => {
  const fake = fakeRefresher();
  const restore = S.useWafRefresher(fake.refresher);
  try {
    const account = { id: 'dead', file: '/tmp/accounts/dead.json', config: {}, cooldownUntil: 0, failures: 0 };
    S.markAccountFailure(account, 401, 'completion', null, AUTH_JSON);
    assert.equal(account.cooldownReason, 'auth');
    assert.ok(account.cooldownUntil - Date.now() > 60_000, 'an expired token is not a WAF blip');
    assert.deepEqual(fake.triggered, []);
  } finally {
    restore();
  }
});

test('repeat throttles back off geometrically, Retry-After still wins, success resets', () => {
  const account = { id: 'hot', cooldownUntil: 0 };
  const first = S.markAccountRateLimited(account, 'too frequent', null, 429, 'completion');
  assert.equal(account.rateLimitStreak, 1);
  const second = S.markAccountRateLimited(account, 'too frequent', null, 429, 'completion');
  assert.equal(account.rateLimitStreak, 2);
  assert.equal(second, first * 2, 'the second consecutive throttle waits twice as long');
  const third = S.markAccountRateLimited(account, 'too frequent', null, 429, 'completion');
  assert.ok(third >= second, 'backoff never shrinks');
  assert.ok(third <= 30 * 60 * 1000, 'backoff is capped below the ceiling');

  assert.equal(S.markAccountRateLimited(account, '429', '42', 429, 'completion'), 42_000,
    'an explicit Retry-After is honored exactly');

  S.recordAccountSuccess(account);
  assert.equal(account.rateLimitStreak, 0, 'a served request clears the streak');
});

test('maybeAutoRefreshWaf only queues a real WAF page, once per account file', () => {
  const fake = fakeRefresher();
  const restore = S.useWafRefresher(fake.refresher);
  try {
    const account = { id: 'x', file: '/tmp/x.json' };
    S.maybeAutoRefreshWaf(account, 401, AUTH_JSON);
    S.maybeAutoRefreshWaf(account, 429, CLOUDFRONT_BLOCK);
    S.maybeAutoRefreshWaf({ id: 'no-file' }, 401, CLOUDFRONT_BLOCK);
    assert.deepEqual(fake.triggered, [], 'nothing to refresh without a WAF page and a file');

    S.maybeAutoRefreshWaf(account, 401, CLOUDFRONT_BLOCK);
    assert.deepEqual(fake.triggered, ['/tmp/x.json']);
  } finally {
    restore();
  }
});

