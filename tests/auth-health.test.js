test('a 401 whose body is a WAF page is a WAF failure, not a dead login', () => {
  assert.equal(health.isWafFailure(401, CLOUDFRONT_BLOCK), true);
  assert.equal(health.isWafFailure(403, CLOUDFRONT_BLOCK), true);
  assert.equal(health.isWafFailure(401, '<meta http-equiv="x-amzn-waf-action">'), true);
  assert.equal(health.isWafFailure(401, AUTH_JSON), false, 'a DeepSeek auth envelope is a real auth failure');
  assert.equal(health.isWafFailure(429, CLOUDFRONT_BLOCK), false, 'only 401/403 reach the WAF path');
  assert.equal(health.isWafFailure(500, CLOUDFRONT_BLOCK), false);
});

test('classifyProbe names each state the checker reports', () => {
  const cases = [
    [{ status: 200, body: CHALLENGE_JSON }, 'ok'],
    [{ status: 429, body: 'too many requests' }, 'ratelimit'],
    [{ status: 400, body: 'Слишком частые сообщения. Повторите попытку позже' }, 'ratelimit'],
    [{ status: 401, body: CLOUDFRONT_BLOCK }, 'waf'],
    [{ status: 403, body: CLOUDFRONT_BLOCK }, 'waf'],
    [{ status: 200, body: AUTH_JSON }, 'auth'],
    [{ status: 401, body: '{"msg":"unauthorized"}' }, 'auth'],
    [{ status: 502, body: 'bad gateway' }, 'upstream'],
    [{ status: 0, networkError: 'fetch failed' }, 'network'],
  ];
  for (const [input, expected] of cases) {
    assert.equal(health.classifyProbe(input).kind, expected, JSON.stringify(input).slice(0, 80));
  }
});

test('probeAccount folds status, Retry-After and latency into one row', async () => {
  const calls = [];
  const fakeFetch = async (url, options) => {
    calls.push({ url, auth: options.headers.Authorization, body: options.body });
    return res('too many requests', 429, { 'retry-after': '42' });
  };
  const row = await health.probeAccount({ token: 'tok', cookie: 'c=1' }, { fetchImpl: fakeFetch });
  assert.equal(row.kind, 'ratelimit');
  assert.equal(row.status, 429);
  assert.equal(row.retryAfterSec, 42);
  assert.equal(typeof row.latencyMs, 'number');
  assert.match(calls[0].url, /create_pow_challenge$/);
  assert.equal(calls[0].auth, 'Bearer tok');
  assert.deepEqual(JSON.parse(calls[0].body), { target_path: '/api/v0/chat/completion' });
});

test('probeAccount reports a network failure without throwing', async () => {
  const row = await health.probeAccount({ token: 't', cookie: 'c' }, {
    fetchImpl: async () => { throw new Error('ECONNRESET'); },
  });
  assert.equal(row.kind, 'network');
  assert.equal(row.status, 0);
  assert.match(row.detail, /|^$/);
});

