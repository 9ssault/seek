test('regression: the WAF refresh never injects ds_session_id before the challenge', () => {
  const source = fs.readFileSync(path.join(__dirname, '..', 'scripts', 'refresh_waf_tokens.js'), 'utf8');
  assert.equal(/Network\.setCookie/.test(source), false, 'the refresh must not set any cookie over CDP');
  assert.equal(/ds_session_id/.test(source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')),
    false, 'the refresh must not touch ds_session_id outside its explanatory comments');
  assert.match(source, /xvfb-run/, 'Linux runs a real browser on a virtual display, not a headless one');
});

