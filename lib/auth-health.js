'use strict';

// Health checks for DeepSeek Web logins: is this account serving, is it throttled,
// is it parked behind an AWS WAF challenge, and is its session a real signed-in
// user or an anonymous one?
//
// Kept out of server.js so the rate-limit checker (scripts/ratelimit_check.js),
// the login capture (scripts/deepseek_chrome_auth.js) and the proxy itself all use
// one definition of each state instead of three drifting ones.

const BASE_URL = 'https://chat.deepseek.com';
const POW_PATH = '/api/v0/chat/create_pow_challenge';
const USERS_PATH = '/api/v0/users/current';

const DEFAULT_UA =
    'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/156.0.0.0 Safari/537.36';

// CloudFront / AWS WAF answers a browser-looking request it does not trust with a
// challenge page ("Request blocked", or the JS challenge shell) instead of letting
// the request reach DeepSeek. That is not an expired login.
const WAF_MARKERS = /x-amzn-waf-action|aws-waf-token|challenge-container|request blocked|generated by cloudfront/i;

// Text DeepSeek uses when it throttles a login, in the languages seen in the wild.
const THROTTLE_TEXT = /too (?:many|frequent)|rate.?limit|слишком част|请求(?:过于)?频繁|请求过多|回数が多|tempo.*limite/i;

function buildHeaders(auth = {}, { ua = DEFAULT_UA } = {}) {
    return {
        'User-Agent': ua,
        'x-client-platform': 'web',
        'x-client-version': '2.4.2',
        'x-client-locale': 'en',
        'x-client-timezone-offset': '-240',
        'x-app-version': '2.4.2',
        Authorization: `Bearer ${auth.token || ''}`,
        'x-hif-dliq': auth.hif_dliq || '',
        'x-hif-leim': auth.hif_leim || '',
        Origin: BASE_URL,
        Referer: `${BASE_URL}/`,
        Cookie: auth.cookie || '',
        'Content-Type': 'application/json',
    };
}

function textOf(value) {
    if (value == null) return '';
    if (typeof value === 'string') return value;
    try {
        return JSON.stringify(value);
    } catch (err) {
        return String(value);
    }
}

function isWafChallengePage(body) {
    return WAF_MARKERS.test(textOf(body));
}

// A 401/403 whose body is a WAF page, not a DeepSeek error envelope.
function isWafFailure(status, detail) {
    const code = Number(status);
    if (code !== 401 && code !== 403) return false;
    return isWafChallengePage(detail);
}

function looksRateLimited(detail) {
    return THROTTLE_TEXT.test(textOf(detail));
}

function bizCode(body) {
    const text = textOf(body).trim();
    if (!text.startsWith('{')) return 0;
    try {
        const payload = JSON.parse(text);
        const inner = Number(payload?.data?.biz_code);
        if (Number.isFinite(inner) && inner !== 0) return inner;
        const outer = Number(payload?.code);
        return Number.isFinite(outer) ? outer : 0;
    } catch (err) {
        return 0;
    }
}

function parseRetryAfterSec(raw) {
    if (!raw) return null;
    const text = String(raw).trim();
    if (/^\d+$/.test(text)) return Number(text);
    const at = Date.parse(text);
    if (Number.isNaN(at)) return null;
    return Math.max(1, Math.ceil((at - Date.now()) / 1000));
}

// One probe response folded into the state the caller cares about.
// kinds: ok | ratelimit | waf | auth | upstream | http | network | unknown
function classifyProbe({ status, body = '', networkError = null } = {}) {
    if (networkError) return { kind: 'network', retryAfterSec: null, note: String(networkError) };
    const code = Number(status) || 0;
    const text = textOf(body);
    if (code === 429 || looksRateLimited(text)) {
        return { kind: 'ratelimit', retryAfterSec: null, note: '' };
    }
    if (isWafFailure(code, text)) return { kind: 'waf', retryAfterSec: null, note: 'WAF challenge' };
    const biz = bizCode(text);
    if (biz >= 40001 && biz <= 40003) return { kind: 'auth', retryAfterSec: null, note: `biz_code ${biz}` };
    if (code === 401 || code === 403) return { kind: 'auth', retryAfterSec: null, note: `HTTP ${code}` };
    if (code >= 500) return { kind: 'upstream', retryAfterSec: null, note: `HTTP ${code}` };
    if (/challenge/i.test(text)) return { kind: 'ok', retryAfterSec: null, note: '' };
    if (code >= 400) return { kind: 'http', retryAfterSec: null, note: `HTTP ${code}` };
    if (!text.trim() || !text.trim().startsWith('{')) return { kind: 'unknown', retryAfterSec: null, note: 'unexpected body' };
    return { kind: 'unknown', retryAfterSec: null, note: 'no challenge in response' };
}

async function readJson(res) {
    const text = await res.text();
    try {
        return { text, json: JSON.parse(text) };
    } catch (err) {
        return { text, json: null };
    }
}

// A PoW challenge is the cheapest request that requires working credentials: it
// costs no generation quota and answers with the same auth/rate-limit signals.
async function probeAccount(auth, { fetchImpl = globalThis.fetch, timeoutMs = 15000, targetPath = '/api/v0/chat/completion' } = {}) {
    const startedAt = Date.now();
    try {
        const res = await fetchImpl(`${BASE_URL}${POW_PATH}`, {
            method: 'POST',
            headers: buildHeaders(auth),
            body: JSON.stringify({ target_path: targetPath }),
            signal: AbortSignal.timeout(timeoutMs),
        });
        const { text } = await readJson(res);
        const verdict = classifyProbe({ status: res.status, body: text });
        return {
            ...verdict,
            status: res.status,
            retryAfterSec: verdict.kind === 'ratelimit'
                ? parseRetryAfterSec(res.headers?.get?.('retry-after'))
                : null,
            latencyMs: Date.now() - startedAt,
            detail: text.slice(0, 300),
        };
    } catch (err) {
        const verdict = classifyProbe({ networkError: err?.name === 'TimeoutError' ? 'timed out' : err?.message || 'network error' });
        return { ...verdict, status: 0, latencyMs: Date.now() - startedAt, detail: '' };
    }
}

// Whether the captured cookie/token belong to a signed-in user. Anonymous sessions
// are what leave the browser on /sign_in and capture a token-less auth file.
async function fetchIdentity(auth, { fetchImpl = globalThis.fetch, timeoutMs = 15000 } = {}) {
    try {
        const res = await fetchImpl(`${BASE_URL}${USERS_PATH}`, {
            method: 'GET',
            headers: buildHeaders(auth),
            signal: AbortSignal.timeout(timeoutMs),
        });
        const { json, text } = await readJson(res);
        if (!json || typeof json !== 'object') {
            return { loggedIn: false, verified: true, reason: isWafChallengePage(text) ? 'WAF challenge' : 'not signed in' };
        }
        const data = json?.data?.biz_data;
        if (!data || typeof data !== 'object') {
            return { loggedIn: false, verified: true, reason: json?.data?.biz_msg || json?.msg || 'not signed in' };
        }
        return {
            loggedIn: Boolean(data.id || data.email || data.mobile),
            verified: true,
            id: data.id || null,
            email: data.email || null,
            mobile: data.mobile || null,
            name: data.email || data.mobile || null,
        };
    } catch (err) {
        // No answer at all: the capture is unverified, not proven anonymous.
        return { loggedIn: false, verified: false, reason: err?.name === 'TimeoutError' ? 'timed out' : err?.message || 'network error' };
    }
}

// One queued browser run at a time per account file, with a cool-down between
// attempts so a burst of 401s cannot spawn a browser per failed request.
function createWafAutoRefresher({
    runRefresh,
    onRefreshed = async () => {},
    onError = () => {},
    now = Date.now,
    cooldownMs = 5 * 60 * 1000,
    historyLimit = 20,
} = {}) {
    const inFlight = new Map();
    const lastAttempt = new Map();
    const history = [];

    function record(entry) {
        history.unshift({ ...entry, at: now() });
        if (history.length > historyLimit) history.length = historyLimit;
    }

    function trigger(file) {
        if (!file) return { started: false, reason: 'no_file' };
        if (inFlight.has(file)) return { started: false, reason: 'in_flight', promise: inFlight.get(file) };
        const since = lastAttempt.get(file);
        if (since != null && now() - since < cooldownMs) {
            return { started: false, reason: 'cooldown', retryInMs: cooldownMs - (now() - since) };
        }
        lastAttempt.set(file, now());
        const promise = (async () => {
            try {
                const ok = await runRefresh(file);
                record({ file, ok: Boolean(ok) });
                if (ok) await onRefreshed({ file });
                return Boolean(ok);
            } catch (err) {
                record({ file, ok: false, error: err?.message || 'refresh failed' });
                onError(err, file);
                return false;
            } finally {
                inFlight.delete(file);
            }
        })();
        inFlight.set(file, promise);
        return { started: true, promise };
    }

    return {
        trigger,
        isRunning: () => inFlight.size > 0,
        history: () => history.slice(),
        stats: () => ({ running: [...inFlight.keys()], history: history.slice() }),
    };
}

module.exports = {
    BASE_URL,
    POW_PATH,
    USERS_PATH,
    DEFAULT_UA,
    buildHeaders,
    isWafChallengePage,
    isWafFailure,
    looksRateLimited,
    classifyProbe,
    probeAccount,
    fetchIdentity,
    parseRetryAfterSec,
    createWafAutoRefresher,
};
