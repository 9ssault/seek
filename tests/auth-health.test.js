const CLOUDFRONT_BLOCK = `<!DOCTYPE HTML PUBLIC "-//W3C//DTD HTML 4.01 Transitional//EN">
<TITLE>ERROR: The request could not be satisfied</TITLE>
<H1>403 ERROR</H1><H2>The request could not be satisfied.</H2>
Request blocked. Generated by cloudfront (CloudFront)`;
const AUTH_JSON = JSON.stringify({ code: 40003, msg: 'token expired', data: { biz_code: 40003 } });
const CHALLENGE_JSON = JSON.stringify({ code: 0, data: { biz_code: 0, biz_data: { challenge: { algorithm: 'x' } } } });

function res(body, status = 200, headers = {}) {
  return new Response(body, { status, headers });
}

